from __future__ import annotations

from itertools import combinations

# 一族至少几条才算一族。两条撞一块儿太常见（全库 `团 == 2` 的屏 99 个，
# 读过的里绝大多数是巧合），三条才开始像「同一句话的多种说法」。
FAMILY_MIN = 3


def measurable(fact) -> bool:
    """这把尺在这条事实上说不说得了话：**两条轴都得有东西**。

    ⚠️ 判不了 ≠ 判「有区别」。判不了的格**整格不进分母**（第 ⑥ 格）。
    """
    return bool(getattr(fact, "obj", ())) and bool(getattr(fact, "topics", ()))


def same_thing(a, b) -> bool:
    """这两条事实说的是不是同一件事：
    `obj` 相交非空 **∧** `topics` 相交非空 **∧ 不是同一场录音**。

    前两条轴的理由在第 ④ 格：单看 `obj`，一个泛 `obj`（`app` / `product` / `kol`）
    就能把三条各说各的事撑成一个团；单看 `topics` 连正反例都分不开（两边都是团 4）。

    ⚠️ **第三条是 P96 加的**（`a.unit != b.unit`），它就是 P94 记在
    `test_p94::第一条c` 里那一版 `M`。P94 量过它「十组正反例全对、反例还更低」，
    **当时判「不要」**，理由是「同一场录音里的重复说法也是灌屏」。
    P96 把分母换成**读过的那 18 屏**（不是十组手挑的正反例）重量了一遍，
    判翻过来了，全文在第 ⑦ 格：**5/6 屏假阳性是靠它治好的，代价是 1 屏真的（i=94）**。
    """
    return (bool(set(a.obj) & set(b.obj))
            and bool(set(a.topics) & set(b.topics))
            and a.unit != b.unit)


def largest_family(facts) -> list[int]:
    """一屏里**最大的一族**，回的是在 `facts` 里的下标（**量得了的格之间**算）。

    取**最大团**（两两都判「没区别」）而不是最大连通块：连通块会串——
    a 和 b 靠一条轴连上、b 和 c 靠另一条连上，而 a 和 c 其实不沾。
    **全库量过这一刀**（`<scratch>/p94/compvsclique.py`，同一份判据只换这一处）：
    **团版判出 18 屏、连通块版 23 屏**，多出来的 5 屏是 **i=24 / 82 / 88 / 412 / 418**——
    **逐条读完，5 屏全是假**（i=82/412 和 i=88/418 是同一批华为 950 超节点的事实：
    「超节点由哪些刀片构成」/「一个计算柜装几片」/「鲲鹏 CPU 和昇腾 NPU 两条芯片线」
    靠 `server`、`chip` 串成一条链，其实是三件不同的事；i=24 是寄 KOL 的时间安排、
    6–7 月出第一款产品、按 4 月 20 日倒排的三件事靠 `product`、`crowdfunding_page` 串起来）。
    ⇒ **换成连通块，`terrence` 上的假阳性 6 → 10、`terrence-rewrite` 上 0 → 1，一屏都没多抓对。**
    （`test_p94::第一条b` 钉着这一格。）

    ⚠️ **判据 K 上这一刀比单轴 `obj` 上小得多**：单轴那一版 `i=591` 那三条是**三角形**
    （每一对都沾一个不同的 obj），团和连通块都给 3——**「串」这件事在单轴上根本不是链，
    是真的两两相交**。这一条是这一批自己先说错、量完改过来的（见第 ④ 格的表）。
    """
    idx = [i for i, f in enumerate(facts) if measurable(f)]
    for size in range(len(idx), 0, -1):
        for combo in combinations(idx, size):
            if all(same_thing(facts[a], facts[b]) for a, b in combinations(combo, 2)):
                return list(combo)
    return []


def family_cover(facts, fam) -> int:
    """**这一族自己的那个话题码，在这一屏上盖着几格**（P98 加的）。

    团里每一条都挂着的话题码（可能不止一个，取盖得最宽的那个）在**量得了的格**里
    出现几次。团 < `FAMILY_MIN` 时回 0（没有团就没有「这一族的话题码」）。

    ⚠️ **必须是团自己的共同码，不是这一屏最主导的码。** 这一条是量出来的，
    不是想出来的：拿「屏上最主导的 topic」当门（候选 `D`），en060 的 i=641
    会放行，而那一屏的主导码 `product_strategy`（4/8）盖的**是另一族**
    （`1458F17`/`1814F9`/`1458F12`/`1589F9`），跟团里那三条基本不是同一批。
    拴在团自己身上（候选 `G`）之后，那一屏的共同码 `memory_powered_intelligence`
    只盖 3 格，不放行 —— **两版在 HEAD 上读数一模一样，只有 en060 那一屏分得开**。
    """
    if len(fam) < FAMILY_MIN:
        return 0
    common: set | None = None
    for i in fam:
        t = set(facts[i].topics)
        common = t if common is None else (common & t)
    idx = [i for i, f in enumerate(facts) if measurable(f)]
    best = 0
    for t in (common or set()):
        best = max(best, sum(1 for i in idx if t in facts[i].topics))
    return best


def screen_shape(facts) -> dict:
    """一屏的形状。

    `{"slots", "measurable", "family", "family_idx", "cover", "flagged"}`。

    `flagged` = **这一屏有半屏是同一句话的多种说法**：最大团 `>= FAMILY_MIN`
    且 **（`团 × 2 >= 量得了的格数` 或 `这一族的话题码盖住的格 × 2 >= 量得了的格数`）**。

    ⚠️ 后面那半句是 **P98 换上去的**（第 ⑧ 格），理由一句话：
    **团是这一族大小的下界，不是这一族本身**（`topics` 会把同一族劈开，第 ⑦-e 格实拍），
    拿一个被压小的数去跟整屏比，这道门就会**在真的灌屏上关着**。
    """
    fam = largest_family(facts)
    n = sum(1 for f in facts if measurable(f))
    cover = family_cover(facts, fam)
    return {"slots": len(facts), "measurable": n,
            "family": len(fam), "family_idx": fam, "cover": cover,
            "flagged": n >= FAMILY_MIN and len(fam) >= FAMILY_MIN
            and (len(fam) * 2 >= n or cover * 2 >= n)}
