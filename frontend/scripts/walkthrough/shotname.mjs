/** 截图名里的**批次前缀**（P74 问题 #6 / P76 C①）。
 *
 * ── 那笔旧账长什么样 ─────────────────────────────────────────────────────
 * 30 份步骤脚本里的截图名**写死成 `p70-*`**（`bnew.mjs` 里 7 张、`b1old.mjs` 里 6 张、
 * `b3old.mjs` 里 6 张……）。于是每一批走查跑完都要**事后手工改名**：
 * P74 那一批改了 36 张。改名这件事本身没危险，危险的是**漏改**——
 * 台账上写着 `p74-b1-old-dark.png`，盘上那张其实是 P70 拍的，
 * 而截图是走查唯一的物证（`d.shot()` 的「不许静默覆盖」正是为这件事立的）。
 *
 * ── 为什么不去改那 30 份 ─────────────────────────────────────────────────
 * 顺手的做法是把 30 份里的 `p70-` 全改成 `p76-`。**那不是修，是把同一个洞挪了一批**：
 * 下一批还得再改一遍 36 张，而且每改一次就多一次漏改的机会。
 * 更要紧的是，P74 刚立了「**步骤脚本一个字节不改**」那条规矩（假壳那条闸靠它
 * 才敢说「跑的是走查本来就在跑的那几步」），为了改个名字把 30 份全动一遍，
 * 等于用一件小事把那条规矩作废掉。
 *
 * **所有截图只有一条出口**：`cdp.mjs` 的 `d.shot(name)`。
 * 批次前缀在这儿换，30 份步骤脚本**一个字节不用动**，而且「名字从参数来」
 * 这件事从此是**结构性的**，不靠谁记得改。
 *
 * ── 规矩 ─────────────────────────────────────────────────────────────────
 *  · `WALKTHROUGH_SHOT_PREFIX` **没设 → 原样不动**。老批次的跑法逐字复现得出来，
 *    这一份不许改变任何已经存在的行为。
 *  · 设了 → 只换**开头那一段 `p<数字>-`**。名字里不带批次前缀的（比如
 *    `debug.png`）**原样不动**：给它硬加一个前缀，等于这把尺子自己造名字。
 *  · 只动开头那一处。`p70-b8-flipday-1-light.png` 里后面的数字一个都不许碰。
 */

/** 名字开头那一段批次前缀长什么样：`p` + 至少一位数字 + `-`。 */
export const BATCH_PREFIX = /^p\d+-/

/**
 * @param {string} name 调用方给的截图名（可能是相对名，也可能是绝对路径）
 * @param {string|undefined} prefix 这一批的前缀，比如 `p76`（带不带末尾的 `-` 都行）
 * @returns {string} 换过前缀的名字
 */
export function withBatchPrefix(name, prefix) {
  if (!prefix || !String(prefix).trim()) return name
  const p = String(prefix).trim().replace(/-+$/, '')
  // 绝对路径：只动**最后一段**，目录名里碰巧长得像前缀的不许动
  const cut = name.lastIndexOf('/')
  const dir = cut >= 0 ? name.slice(0, cut + 1) : ''
  const base = cut >= 0 ? name.slice(cut + 1) : name
  if (!BATCH_PREFIX.test(base)) return name
  return dir + base.replace(BATCH_PREFIX, `${p}-`)
}
