"""这篇 → 幻灯片（痛点 6，docs/slides-plan.md）。

痛点原话是「想做成 PPT，又要上传给另一个 agent 工具，**两个工具之间没有链接**」。
所以这份提示词里最要紧的一条不是排版，是**把正文里的引用标记原样带到对应页**
——每一页都能点回它的依据，这是这个产品跟通用 PPT 工具的根本差别。

一次模型调用，不进多轮闭环：幻灯片是一次成型的重构，多轮只会把页越改越碎。
"""

from __future__ import annotations

from .fragments import content_block

SLIDES_SYSTEM = """你把一篇笔记改写成一份幻灯片。输出 Marp 风格的 markdown：
开头一段 front-matter，之后每一页之间用单独一行 `---` 隔开。

```
---
marp: true
slides: true
---

# 笔记标题

一句话结论。

---

## 这一页要讲的那个判断

- 要点
- 要点
```

硬要求：

- **每页只讲一件事。** 页标题是一个完整的判断句（「EVT 节点从 6 月挪到 8 月」），
  不是名词短语（「EVT 节点」）——名词短语等于让读者自己猜结论。
- **正文里的 [事实编号] 原样带到对应页**，一个字都不要改。这是这份幻灯片跟
  通用工具做出来的东西唯一的区别：每一页都能点回它的依据。编号只能从正文里抄。
- 正文里已经有的 ```mermaid 图**整块搬**到它该在的那一页，不要重画、不要改。
- 每页要点 3–5 条，每条不超过 40 字。超了就**拆成两页**，不要把字缩短。
- 首页是标题页：笔记标题 + 一句话结论。末页是「还缺什么」：正文里写着待核实的、
  或者没有依据支撑的判断。
- 页数按内容定，通常 8–20 页。正文短就少给几页，**不要注水**。
- 不要写演讲备注，不要写「谢谢观看」，不要自己发明正文里没有的数字或结论。

直接输出 markdown，不要任何额外解释或前后缀。
"""

# 讲稿风格：每页下面多一段口语化的话。**不是另一套结构**——同样的页、同样的
# 引用，只是多了讲的时候说什么。分成两个 style 是因为这两种用途对页面密度的
# 要求正好相反：要点版页面要空，讲稿版可以密一点。
SLIDES_TALK_EXTRA = """
另外：每一页的要点下面，空一行再写一段 `> ` 开头的讲稿，两三句口语化的话，
说清楚这一页为什么重要。讲稿不进要点、不影响每页 3–5 条那条限制。
"""


def slides_user(title: str, content: str, style: str = "points") -> str:
    parts = [f"笔记标题：{title}" if title else "", content_block(content)]
    parts.append("把上面这篇笔记改写成幻灯片。"
                 + ("要点版：页面留白，一句话一个要点。" if style != "talk"
                    else "讲稿版：每页要点下面带一段讲稿。"))
    return "\n\n".join(p for p in parts if p)
