test('failed index commits preserve previous memory, metadata and original files', async t => {
  const stateDirectory = directory()
  const store = new CompanionStore(stateDirectory)
  const existing = store.addText('saved entry')
  const index = path.join(stateDirectory, 'shelf.json')
  const previous = readFileSync(index, 'utf8')
  const file = original()
  const rename = fs.renameSync
  t.mock.method(fs, 'renameSync', (from, to) => {
    if (to === index) throw new Error('simulated index rename failure')
    return rename(from, to)
  })
  assert.throws(() => store.addText('unsaved entry'))
  await assert.rejects(() => store.addFiles([file]))
  const vault = path.join(stateDirectory, 'vault')
  const beforeImage = existsSync(vault) ? fs.readdirSync(vault) : []
  assert.throws(() => store.addImage(Buffer.from('89504e470d0a1a0a', 'hex')))
  assert.deepEqual(existsSync(vault) ? fs.readdirSync(vault) : [], beforeImage, 'failed image commits clean their unindexed copy')
  assert.equal(store.list().length, 1)
  assert.equal(store.get(existing.id).text, 'saved entry')
  assert.equal(readFileSync(index, 'utf8'), previous)
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  assert.ok(store.storageError)
  assert.equal(new CompanionStore(stateDirectory).list().length, 1)
})

