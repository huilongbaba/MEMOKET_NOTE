test('the IPC boundary admits only the owned main frame at the current backend origin and surface', () => {
  const contents = {}
  const mainFrame = {}
  const event = { sender: contents, senderFrame: mainFrame }
  const expected = { contents, mainFrame, frameUrl: 'http://127.0.0.1:47232/?user=test&surface=top', baseUrl: 'http://127.0.0.1:47232/?user=test', surface: 'top' }
  assert.equal(trustedCompanionFrame(event, expected), true)
  assert.equal(trustedCompanionFrame({ ...event, sender: {} }, expected), false)
  assert.equal(trustedCompanionFrame({ ...event, senderFrame: {} }, expected), false)
  assert.equal(trustedCompanionFrame({ ...event, senderFrame: null }, expected), false)
  for (const frameUrl of ['http://127.0.0.1:47231/?surface=top', 'https://example.com/?surface=top', 'file:///tmp/index.html?surface=top', 'http://127.0.0.1:47232/api/notes?surface=top', 'http://127.0.0.1:47232/?surface=shelf', 'http://127.0.0.1:47232/']) {
    assert.equal(trustedCompanionFrame(event, { ...expected, frameUrl }), false, frameUrl)
  }
  assert.equal(trustedCompanionFrame(event, { ...expected, baseUrl: 'https://example.com/' }), false)
})

