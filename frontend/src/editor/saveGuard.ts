/** 「别把更短的正文盖回刚交稿的那一份」——`save()` 的那条护栏（P70 B）。
 *
 * ## 为什么需要它
 *
 * P68 修的是**源头**（编辑器把自己刚同步进去的那一份原样回声回去，流式写入时
 * 把刚到的那一片盖回上一片）。实拍那一格：后端交出去并且已经 commit 进库的是
 * **1103 字**，编辑器里只剩 **807**，1.5 秒后**自动保存把 807 写回了库**，
 * 把后端刚落的那一份盖掉——用户眼前少掉 296 个字，界面上同时还摆着「+1060 字」。
 *
 * 源头修好了，**这条路本身仍然没有护栏**：只要 React 那边的 `content` 因为任何
 * 原因落在服务端刚交的那一份后面，1.5 秒后的自动保存照样会把短的那一份写回去。
 *
 * ## 判据宁可窄
 *
 * **用户自己删字是正当的，一次都不许拦。** 所以判据不是「变短了就拦」，而是
 * 「**用户没动，而它变短了**」——三条同时成立：
 *
 *   ① 锚点是**这一篇**的（`served.id === noteId`）；
 *   ② 自那一份交下来之后，编辑器**一次改动都没报过**（`edits === 0`）；
 *   ③ 要存的这一份**比它短**。
 *
 * ②那一条是承重的：用户敲的字、悬停工具条上的「接受 / 撤回」、「全部撤回」、
 * `/` 菜单的块、粘贴——**每一条都经过 CodeMirror**，都会让 `onChange` 报一次
 * （回声不报，`editor/syncEcho.ts` 已经把它挡在外面了）。所以只要用户真动过一下，
 * `edits` 就不是 0，这条护栏一次都碰不到他。
 *
 * P70 的量具（`__tests__/p70.test.tsx`，真 React 19 + 真 CM 6）逐格量过：
 *
 * | | 情形 | `edits` | 护栏 |
 * |---|---|---:|---|
 * | B1 | 用户自己删字 | 1 | 照写 |
 * | B2 | 「全部撤回」那一类程序化 dispatch | 1 | 照写 |
 * | B3 | 服务端刚交完，过期的镜像把 `content` 拉回短的 | **0** | **★挡下** |
 * | B4 | CM 在同步那一条事务上又改了一道（P70 A 的第二半） | 1 | 照写 |
 * | B5 | 交完之后打开别的一篇（更短） | 0（锚点换了） | 照写 |
 * | B6 | 服务端自己交了更短的一份（清洗 / 去重） | 0（锚点换了） | 照写 |
 */

/** 服务端 / 流式**最后交给这一篇**的那一份正文，以及自那以后编辑器报了几次改动。 */
export interface Served {
  /** 这份正文是哪一篇的。`open()` 写；空串 = 还没有锚点。 */
  id: string
  /** 那一份正文本身。 */
  text: string
  /** 自那一份交下来之后，编辑器报上来的改动次数（**回声不算**）。 */
  edits: number
}

/** 要存的这一份是不是「用户没动，而它变短了」。true = 别写它，写 `served.text`。 */
export function isStaleShrink(served: Served, noteId: string, content: string): boolean {
  if (!served.id || served.id !== noteId) return false     // ① 锚点得是这一篇的
  if (served.edits !== 0) return false                     // ② 用户动过一下就不拦
  return content.length < served.text.length               // ③ 比刚交的那一份短
}
