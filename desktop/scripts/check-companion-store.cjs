/** Pure local tests. No Electron process, clipboard, OS window or personal data is accessed. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, unlinkSync, symlinkSync, rmSync } = fs
const { tmpdir } = require('node:os')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { test, after } = require('node:test')
const { CompanionStore, webLink } = require('../dist/companion-store.js')
const { trustedCompanionFrame, validWorkspaceDestination } = require('../dist/companion-boundary.js')

const temporary = mkdtempSync(path.join(tmpdir(), 'memoket-companion-store-'))
after(() => rmSync(temporary, { recursive: true, force: true }))
const directory = () => path.join(temporary, randomUUID())
function original(name = 'plan.txt') {
  const parent = directory()
  mkdirSync(parent)
  const file = path.join(parent, name)
  writeFileSync(file, 'original content')
  return file
}

test('file snapshots persist across restart and deduplicate only within a single explicit drop', async () => {
  const stateDirectory = directory()
  const file = original()
  const store = new CompanionStore(stateDirectory)
  const [added] = await store.addFiles([file, file])
  assert.equal(store.list().length, 1)
  assert.equal(store.storageError, '')
  assert.equal(added.storage, 'copy')
  assert.equal(added.sourcePath, file)
  assert.equal(added.path, path.join(stateDirectory, 'vault', added.id, path.basename(file)))
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  assert.equal(readFileSync(added.path, 'utf8'), 'original content')
  writeFileSync(file, 'next snapshot')
  const [again] = await store.addFiles([file])
  assert.notEqual(again.id, added.id)
  assert.notEqual(again.path, added.path)
  assert.equal(readFileSync(again.path, 'utf8'), 'next snapshot')
  assert.equal(readFileSync(added.path, 'utf8'), 'original content')
  const restored = new CompanionStore(stateDirectory)
  assert.equal(restored.list().length, 2)
  assert.equal(restored.get(added.id).path, added.path)
  assert.equal(restored.get(again.id).sourcePath, file)
  assert.equal(restored.list().every(item => item.storage === 'copy' && item.missing === false), true)
})

test('changing or deleting an original does not alter its saved snapshot or mark the snapshot missing', async () => {
  const stateDirectory = directory()
  const file = original('photo.png')
  const store = new CompanionStore(stateDirectory)
  const [item] = await store.addFiles([file])
  writeFileSync(file, 'changed original')
  assert.equal(readFileSync(item.path, 'utf8'), 'original content')
  unlinkSync(file)
  const restored = new CompanionStore(stateDirectory)
  assert.equal(restored.list()[0].kind, 'image')
  assert.equal(restored.list()[0].missing, false)
  assert.equal(restored.get(item.id).path, item.path)
  assert.equal(restored.get(item.id).sourcePath, file)
  assert.equal(readFileSync(item.path, 'utf8'), 'original content')
  assert.equal(existsSync(file), false)
})

test('copies complete folder trees independently, including nested files and empty folders', async () => {
  const folder = directory()
  mkdirSync(path.join(folder, 'nested', 'empty'), { recursive: true })
  writeFileSync(path.join(folder, 'nested', 'plan.txt'), 'folder snapshot')
  const store = new CompanionStore(directory())
  const [item] = await store.addFiles([folder])
  assert.equal(item.storage, 'copy')
  assert.equal(readFileSync(path.join(item.path, 'nested', 'plan.txt'), 'utf8'), 'folder snapshot')
  assert.equal(existsSync(path.join(item.path, 'nested', 'empty')), true)
  writeFileSync(path.join(folder, 'nested', 'plan.txt'), 'source changed')
  rmSync(folder, { recursive: true })
  assert.equal(readFileSync(path.join(item.path, 'nested', 'plan.txt'), 'utf8'), 'folder snapshot')
  assert.equal(store.list()[0].missing, false)
  const exported = await store.prepareExport(item.id)
  writeFileSync(path.join(exported, 'nested', 'plan.txt'), 'destination edit')
  rmSync(exported, { recursive: true })
  assert.equal(readFileSync(path.join(item.path, 'nested', 'plan.txt'), 'utf8'), 'folder snapshot')
})

test('removing a managed copy moves it to recoverable storage and preserves the original', async () => {
  const stateDirectory = directory()
  const file = original()
  const store = new CompanionStore(stateDirectory)
  const [item] = await store.addFiles([file])
  const removed = await store.remove(item.id)
  assert.equal(removed.recoveryPath, path.join(stateDirectory, 'removed', item.id, path.basename(file)))
  assert.equal(existsSync(item.path), false)
  assert.equal(readFileSync(removed.recoveryPath, 'utf8'), 'original content')
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  const recovery = JSON.parse(readFileSync(path.join(stateDirectory, 'removed', `${item.id}.json`), 'utf8'))
  assert.ok(JSON.stringify(recovery).includes(item.id), 'recovery metadata identifies the removed snapshot')
  assert.ok(JSON.stringify(recovery).includes(file), 'recovery metadata retains the original source path')
  assert.equal(store.list().length, 0)
  assert.equal(new CompanionStore(stateDirectory).list().length, 0)
})

test('old version-one references stay references and removing one never moves or deletes its original', async () => {
  const stateDirectory = directory()
  mkdirSync(stateDirectory)
  const file = original()
  const item = { id: randomUUID(), kind: 'file', title: 'Old reference', path: file, createdAt: new Date().toISOString() }
  writeFileSync(path.join(stateDirectory, 'shelf.json'), JSON.stringify({ version: 1, items: [item] }))
  const store = new CompanionStore(stateDirectory)
  assert.equal(store.get(item.id).path, file)
  assert.notEqual(store.get(item.id).storage, 'copy')
  assert.equal(existsSync(path.join(stateDirectory, 'vault')), false)
  const exported = await store.prepareExport(item.id)
  assert.notEqual(exported, file)
  writeFileSync(exported, 'external edit of a legacy reference export')
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  const removed = await store.remove(item.id)
  assert.equal(removed.recoveryPath, undefined)
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  assert.equal(new CompanionStore(stateDirectory).list().length, 0)
})

test('exports are new independent copies, so editing or deleting them never changes the vault or source', async () => {
  const stateDirectory = directory()
  const file = original()
  const store = new CompanionStore(stateDirectory)
  const [item] = await store.addFiles([file])
  const first = await store.prepareExport(item.id)
  const second = await store.prepareExport(item.id)
  assert.notEqual(first, second)
  assert.equal(path.dirname(path.dirname(first)), path.join(stateDirectory, 'exports'))
  assert.equal(path.basename(first), path.basename(file))
  assert.equal(readFileSync(first, 'utf8'), 'original content')
  writeFileSync(first, 'external application edit')
  unlinkSync(second)
  assert.equal(readFileSync(item.path, 'utf8'), 'original content')
  assert.equal(readFileSync(file, 'utf8'), 'original content')
  assert.equal(store.list()[0].missing, false)
})

test('a directory export is invalidated by a changed child even when its root modification time is unchanged', async () => {
  const folder = directory()
  mkdirSync(path.join(folder, 'nested'), { recursive: true })
  writeFileSync(path.join(folder, 'nested', 'plan.txt'), 'snapshot')
  const store = new CompanionStore(directory())
  const [item] = await store.addFiles([folder])
  const exported = await store.prepareExport(item.id)
  const rootModified = fs.statSync(item.path).mtimeMs
  writeFileSync(path.join(item.path, 'nested', 'plan.txt'), 'changed child with a different size')
  assert.equal(fs.statSync(item.path).mtimeMs, rootModified)
  assert.equal(readFileSync(path.join(exported, 'nested', 'plan.txt'), 'utf8'), 'snapshot')
  assert.equal(store.claimExport(item.id, exported), false)
})

