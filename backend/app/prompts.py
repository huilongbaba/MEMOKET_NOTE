def edit_user(spine: str, beats: list[str], content: str, facts: list[str],
              profile: list[str], focus: str = "", dup_hints: list | None = None,
              outline_note: str = "", defect_lines: list[str] | None = None,
              focus_note: str = "") -> str:
    parts = []
    block = _profile_block(profile)
    if block:
        parts.append(block)
    if outline_note:
        # 用户已有结构的保护说明放最前面——它比其他任何指令都优先
        parts.append(outline_note)
    spine_block = _spine_beats_block(spine, beats)
    if spine_block:
        parts.append(spine_block)
    if facts:
        parts.append("【知识库事实】\n" + "\n".join(f"- {f}" for f in facts))
    else:
        parts.append("【知识库事实】\n（无相关记录）")
    if focus:
        label = _FOCUS_LABELS.get(focus, focus)
        block = (f"【这一轮优先检查】\n上一轮评分里这一项最弱：{label}。"
                 "优先看这个问题有没有解决，其余几条原则仍然适用，但不用逐条重新过一遍。")
        if focus_note:
            # 打分器写的诊断原文。只给维度名的话，修订这一步不知道**哪两段在
            # 重复什么**；而重复往往是语义上的（实测段落两两相似度最高只有
            # 0.29），机械查重的 dup_hints 是空的，这句话是它唯一的具体线索。
            # 实测代价：12 次跑里 7 次第一轮就判 non_repetition=1，然后
            # 1 → 1 → 1，跑完三轮一次都没回到 2。
            block += ("\n打分时具体指出的问题是：" + focus_note
                      + "\n照这句话去正文里找对应的位置，就地改掉。")
        parts.append(block)
    if dup_hints:
        # 机械查重（writer_harness.find_repeats()，不用 LLM）先算好的疑似
        # 重复段落对——真实测试暴露的问题：只让模型自己通读全文找重复，
        # 连续几轮"重复"这条原则都卡住不改善；给具体候选对，比让它每轮
        # 重新从头找一遍更可靠。这是候选，不是定论，还是要模型自己判断
        # 是不是真的在说同一件事、该留哪条。
        pairs = "\n".join(
            f"- 段落A：{h.a[:150]}\n  段落B：{h.b[:150]}（相似度 {h.similarity:.0%}）"
            for h in dup_hints[:5]
        )
        parts.append("【机械查重找到的疑似重复段落，逐条判断是不是真的重复、要不要删一条】\n" + pairs)
    if defect_lines:
        # 确定性扫出来的占位符所在行。跟 dup_hints 同一个套路：规则里早就禁了
        # （"不写空模板占位符、不写编号占位的待办"），20 轮 soak 里照样出了
        # 21 处、单个种子最多 10 处——光在规则里说不管用，得把具体位置指给它。
        parts.append("【这几处必须就地处理】\n"
                     + "\n".join(f"- {d}" for d in defect_lines)
                     + "\n**占位符**：有材料就填实，没材料就把这一行/这一格删掉，"
                       "或者改成「这里需要补上 XX 的实际记录」。"
                       "\n**审计腔/机制泄漏**：删掉关于证据够不够的元评论，也不要在正文里"
                       "出现「知识库」「KB」「检索到的记录」这类词——这是用户自己的笔记，"
                       "不是给第三方看的审计报告。查到什么写什么，查不到就一句"
                       "「这里需要补上 XX 的实际记录」带过。"
                       "\n**一条都不许原样留着。**")
    parts.append("【正文】\n" + content)
    return "\n\n".join(parts)


# 三处续写型 user prompt（magic_tap_user/section_write_user/
# note_harness_continue_user）共用同一条提醒：MAGIC_TAP_SYSTEM 的格式指令
# 是"延续已有格式风格"，但正文里还没出现过任何 "## " 标题时没有风格可
# 延续——实测这会让模型要么整段不分点写成散文，要么用 **加粗** 短语冒充
# 小节标题，跟后面真正用上标题的轮次体例不一致（同一篇笔记一节是"**标题**"
# 另一节是"## 标题"，读起来不像统一体例写出来的）。只在 content 里还没
# 出现过 "##" 时插入，已经有标题的话交给"延续已有风格"那条指令自然管，
# 不用再提醒一遍。
def _heading_format_reminder() -> str:
    return (
        "正文里目前还没有出现过 \"## \" 这种标题——不代表不用格式。内容"
        "如果有并列/递进的小节或要点，照样要用 \"## \" 二级标题分节、"
        "\"- \" 列表分点，不要因为还没有\"已有风格\"可以延续就整段写成"
        "不分点的散文；也不要用 **加粗** 短语冒充小节标题——**加粗**只用来"
        "强调段落里的关键结论，跟标题是两回事，不能一节用标题、另一节用"
        "加粗假装标题。"
    )


def magic_tap_user(spine: str, beats: list[str], content: str, facts: list[str],
                   profile: list[str], folder_context: str = "") -> str:
    parts = []
    block = _profile_block(profile)
    if block:
        parts.append(block)
    spine_block = _spine_beats_block(spine, beats)
    if spine_block:
        parts.append(spine_block)
    if folder_context:
        parts.append(folder_context)
    if facts:
        parts.append("【知识库中的相关事实】\n" + "\n".join(f"- {f}" for f in facts))
    parts.append("【已写正文】\n" + content)
    if "##" not in content:
        parts.append(_heading_format_reminder())
    parts.append("请接着往下写。")
    return "\n\n".join(parts)


# ---------------------------------------------------------------- 单篇笔记 harness
#
# 跟无限续写（writing_plan.py）是同一个"自动修订+自动续写交替、直到内容
# 判定完整才停"的 harness 精神，范围收在一篇笔记内部——不创建新笔记，
# 完成条件是结构节拍（spine/beats）被正文实质覆盖，不是分段列表跑完。
#
# "写完了没有"不再靠续写模型自己在正文末尾主观判断、吐一个标记——见
# writer_harness.evaluate()：改成每轮续写完之后单独跑一次打分，续写这一步
# 只管往下写，不用兼顾"自我判断完不完整"这件事。

RETRIEVAL_PLAN_SYSTEM = """你是写作助手的检索规划环节。给你一篇正在写的
笔记和它接下来要写的方向，你只做一件事：**判断为了写好接下来这部分，
需不需要查用户的个人知识库；需要的话，把该查的一次查完。**

你现在**不需要写正文**，一个字都不用写。这一步的产出就是工具调用本身。

判断依据：
- 接下来要写的内容，是否依赖用户自己的记录——具体的人名、日期、数字、
  某次会议的结论、某个决定的来龙去脉。**这类东西凭空写就是编造**，必须查。
- 正文里已经出现了某个人名、产品名、项目名，接下来要展开它——先查清楚
  用户自己是怎么描述的，别用你以为的定义。
- 如果接下来这部分纯粹是推理、结构、取舍逻辑，不依赖任何具体事实，那就
  不用查，直接回复"不需要检索"。

怎么查——**先看问题是哪一类，再挑工具，不要一律用 search_memory**：

- **「在讨论 X 的那次会里，除了 X 还有什么」「聊 Y 的时候还定了什么」**
  ——需要先定位到某个场合、再看那个场合里还有什么：用 **search_session_context**。
  这类问题 search_memory 做不到，它只会按关键词捞一堆散落各处的事实，
  给不出"同一次会议里的其他内容"。判断标志是问题里有「那次」「上次」
  「当时」「除了…还」这类把范围锚定在某个场合上的说法。
- **知道确切主题 code**（上面主题清单里有的）：用 **filter_facts**，
  按主题精确取，比关键词匹配准得多，不会串味。
- **有明确关键词、就是想捞相关事实**：用 search_memory。它是字面匹配，
  中英混合的长查询容易召回完全不相关的内容，所以关键词要短、要具体。
- **要写某段时间发生了什么**：用 facts_in_range。
- **拿不准某条事实的确切含义**：用 fact_sources 回溯原话。

list_topics / list_entities 只是帮你决定往哪查的**元信息**，它们本身不返回
事实——只调它们就收手，等于什么都没查到。
- 一次把要查的都查了，同一件事不要换几种说法反复查。
- 拿到事实后如果拿不准某条的确切含义，可以用 fact_sources 回溯原话。

宁可多查一点，也不要在该查的时候不查——查不到最多是白花点时间，不查就
会编造，而编造出来的具体日期和人名会被用户当成自己的记录。"""


def retrieval_plan_user(title: str, spine: str, beats: list[str], content: str,
                        steer: str = "", require_verification: bool = False,
                        topics_overview: str = "", section: str = "") -> str:
    """``steer`` 是策略控制器根据上一轮反馈给出的方向（见 runtime_policy.py）。

    它承载的是此前被整个丢掉的信号——打分模型写的自然语言诊断。上一轮说
    "使用了知识库中未出现的具体日期和人物"，这句话原封不动喂回检索规划，
    比只把最弱维度的名字塞进去能指导的多得多。
    """
    parts = []
    if section:
        # 大纲模式下这一轮只写某一节。**检索必须知道是哪一节**，否则每轮都
        # 拿同一批事实，模型只能把同一批材料换个标题再说一遍——20 轮 soak 里
        # non_repetition 是全局最弱的一维（0.9~1.7），大纲组 50 次撞 max_rounds
        # 而 beat_coverage 已经 1.9~2.0，卡住的正是重复。
        parts.append(f"【这一轮只写「{section}」这一节】\n"
                     f"查的材料要针对这一节，不要再取上几轮已经写过的那些。")
    if topics_overview:
        # 主题树直接摆出来，不让它先花一次工具往返去问「知识库里有什么」。
        #
        # 实测的问题：prompt 里明明写了「不确定就先 list_topics」，但六次
        # 检索全是 search_memory，一次都没用过主题树——引导写在文字里，
        # 模型还是走最短路径。而 search_memory 是关键词匹配，中英混合长
        # 查询会串味：查「Speaker C APP 安装 测试」召回的是知识库里《秘密
        # 花园》的英文段落。主题树本身零 LLM、亚毫秒，没有任何理由不直接
        # 给——摆在面前它才会用 filter_facts 按主题精确取。
        parts.append("【这个用户的知识库覆盖哪些主题（括号内是事实条数）】\n"
                     + topics_overview
                     + "\n\n上面这些 code 可以直接作为 filter_facts 的 topic 参数。"
                       "**主题对得上就优先用 filter_facts 按主题取，比 search_memory "
                       "的关键词匹配准得多**——关键词检索在中英混合的长查询上会召回"
                       "完全不相关的内容。")
    if title:
        parts.append(f"【笔记标题】\n{title}")
    block = _spine_beats_block(spine, beats)
    if block:
        parts.append(block)
    parts.append("【已写正文】\n" + (content or "（还没开始写）"))
    if steer:
        parts.append("【上一轮的反馈，这一轮优先处理】\n" + steer)
    if require_verification:
        parts.append("上一轮正文里的具体事实被判为站不住。这一轮凡是要写进正文的"
                     "具体人名、日期、数字，都要先查到出处；拿不准某条事实的确切"
                     "含义就用 fact_sources 回溯原话核对。")
    parts.append("接下来要续写这篇笔记，优先补上结构节拍里还没被正文覆盖的部分。"
                 "现在判断：需要查知识库吗？需要就调用工具，不需要就回复「不需要检索」。")
    return "\n\n".join(parts)


REPLAN_SYSTEM = """你是写作顾问，现在做一件很具体的事：**修正一份已经在用的
结构节拍**。

这份骨架是在正文还很短、还没查知识库的时候定的，掌握的信息比现在少。
现在正文写了一些、可能也检索到了具体材料，回头看会发现有的节拍定错了。
你要做的不是重写骨架，是**改掉错的那几条**。

只能做三种操作：
- ``rewrite``：把某一条节拍改写成更准确的说法（给 index 和新的 text）
- ``drop``：删掉某一条已经被证明不该服务的节拍（给 index）
- ``add``：补一条现有节拍完全没预见到的（给 text）

**绝对不许改核心张力（spine）**。核心张力换了就是另一篇文章，那不叫修正
叫跑题。你手上只有节拍这一层。

什么样的节拍该改：
- **放在任何一篇文章上都成立的修辞功能位**——「建立警示性处境」「预判读者
  追问」「收束呼应并强化行动指令」。它们描述的是通用议论文该长什么样，
  不是这一篇该写什么，正文没法"覆盖"它们，只能不断往上堆套话。改成落在
  具体内容上的说法：「用某某项目的实际成本构成说明物料价之外的开销占多少」。
- **把正文里的毛病当成了写作意图**——编号错序、前后矛盾、层级混乱这些是
  要被修掉的缺陷，不是这篇笔记的目标。发现节拍在要求"以编号错位呈现"
  这类东西，直接 drop。
- **跟检索到的材料对不上**——如果知识库里明明有一块很相关的具体内容，而
  现有节拍一条都没覆盖到它，补一条。

不要为了改而改：只有真的定错了才动，没问题的节拍原样留着不用出现在输出里。
节拍数量不会因为你的新增而变多（新增最多补回你删掉的条数），所以要新增
就先想清楚删哪条。

只输出 JSON 数组，形如：
[{"op": "rewrite", "index": 0, "text": "..."}, {"op": "drop", "index": 3},
 {"op": "add", "text": "..."}]
没有要改的就输出 []。不要任何解释文字。"""


def replan_user(title: str, spine: str, beats: list[str], content: str,
                facts: list[str], why: str) -> str:
    parts = [f"【为什么找你重排】\n{why}"]
    if title:
        parts.append(f"【笔记标题】\n{title}")
    parts.append(f"【核心张力（不许改，只作为判断依据）】\n{spine or '（空）'}")
    parts.append("【现有结构节拍（index 从 0 开始）】\n"
                 + "\n".join(f"{i}. {b}" for i, b in enumerate(beats)))
    if facts:
        parts.append("【这一轮从知识库检索到的材料】\n"
                     + "\n".join(f"- {f}" for f in facts[:12]))
    parts.append("【目前写成的正文】\n" + content)
    return "\n\n".join(parts)


def tools_hint(tool_list: str) -> str:
    """挂在续写 system prompt 后面的工具说明。

    ``tool_list`` 由 app.tools.describe() 渲染，这里不 import tools——
    prompts.py 是纯文本模块，不该知道工具是怎么注册的。

    这段话的重点不是"有哪些工具"（tools 数组里已经有了），而是**什么时候
    该查、什么时候不该查**。实测模型拿到工具后有两种失败倾向：一种是完全
    不用，退回凭空写；另一种是每段话都先查一遍，把一轮续写拖成五分钟。
    """
    return f"""你可以查用户的个人知识库。要不要查、查什么，你自己判断。

可用的工具：
{tool_list}

什么时候该查：
- 要写到用户过往的记录、决定、经历——具体的人名、日期、数字、某次会议的
  结论，这些只有知识库里有，凭空写就是编造
- 正文里已经出现了某个人名或产品名，你要接着展开——先查清楚用户自己是
  怎么描述它的，别用你以为的定义
- 不确定知识库里有没有相关内容——先 list_topics 看一眼比直接猜要好

什么时候不用查：
- 这一段写的是推理、结构、取舍逻辑，不依赖任何具体事实
- 上一轮已经查过同一件事，结果就在上面的对话里，不要重复查

用工具的原则：
- **不要为了用工具而用工具**。判断依据是"这段话需不需要用户自己的记录"，
  不是"我是不是应该表现得勤奋"
- 一次把要查的都查了，不要一个关键词一个关键词地试——每次查询都有实打实
  的时间开销
- **查不到就是查不到，不要编**。宁可把这一段写得抽象一点、或者干脆跳过
  去写别的能写实的部分，也不要虚构具体的人名、日期和数字
- 知识库事实的语言不一定跟正文一致（可能是英文），融进正文前要意译成
  正文的语言，不要把原文语言的句子原样嵌进来"""


