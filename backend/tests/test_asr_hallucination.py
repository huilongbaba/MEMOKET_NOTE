"""Whisper 在静音段上背出来的那几句话，不该进知识库。

第 632 轮在真库上量出来的：20406 条事实里有 16 条是这个——
「请不吝点赞订阅转发打赏支持明镜与点点栏目」×9、「谢谢观看，下次见！」×4、
「这句子是普通话的句子。」×3。录音里根本没人说过这些，是模型在没有语音可转的
地方把训练数据里的视频结尾背了出来。数量不大，但它们**会被召回、会被引用**，
最后写进用户的文稿里。

拦在 `asr.transcribe()`：那是所有转写文本的唯一入口（存知识库、编辑器里的
「语音输入」都走它）。
"""

from __future__ import annotations

from app.database.ingest.asr import drop_hallucinations as drop


def test_整句幻觉被删掉_前后文照旧():
    assert drop("今天定了电池方案。请不吝点赞订阅转发打赏支持明镜与点点栏目。明天继续。") \
        == "今天定了电池方案。明天继续。"
    assert drop("这句子是普通话的句子。我们继续说样机。") == "我们继续说样机。"
    assert drop("谢谢观看，下次见！") == ""


def test_用户自己在说订阅业务的不能误伤():
    """**这条是这个守卫的全部分寸所在。** 第一版用「订阅|谢谢观看|字幕」这种宽
    模式，在真库上一量命中 133 条——一看全是用户在讲他自己的邮件订阅漏斗。
    宽一格就开始误伤，所以只做整句匹配，宁可漏。"""
    for keep in [
        "这里又是一个订阅框",
        "真实的订阅的例子是模拟一个用户从 facebook 的官方账号发一个带跟踪链接的帖子。",
        "订阅流程一直走通，只是无法识别用户来源。",
        "他订阅之后，因为这里面要设置的是那种自动的。",
        "谢谢观看了这个 demo，我们再看下一版。",
    ]:
        assert drop(keep) == keep, keep


def test_空的和只有幻觉的都不炸():
    assert drop("") == ""
    assert drop("谢谢观看，下次见！ 谢谢观看，下次见！") == ""
